// Recipe.swift
import Foundation

struct Recipe: Identifiable, Decodable, Equatable {
    let idRecipe: String
    let strRecipe: String
    let strCategory: String?
    let strArea: String?
    let strInstructions: String?
    let strRecipeThumb: String?
    let strTags: String?
    let strSource: String?
    
    let strIngredient1: String?
    let strIngredient2: String?
    let strIngredient3: String?
    let strIngredient4: String?
    let strIngredient5: String?
    let strIngredient6: String?
    let strIngredient7: String?
    let strIngredient8: String?
    let strIngredient9: String?
    let strIngredient10: String?
    let strIngredient11: String?
    let strIngredient12: String?
    let strIngredient13: String?
    let strIngredient14: String?
    let strIngredient15: String?
    let strIngredient16: String?
    let strIngredient17: String?
    let strIngredient18: String?
    let strIngredient19: String?
    let strIngredient20: String?
    
    let strMeasure1: String?
    let strMeasure2: String?
    let strMeasure3: String?
    let strMeasure4: String?
    let strMeasure5: String?
    let strMeasure6: String?
    let strMeasure7: String?
    let strMeasure8: String?
    let strMeasure9: String?
    let strMeasure10: String?
    let strMeasure11: String?
    let strMeasure12: String?
    let strMeasure13: String?
    let strMeasure14: String?
    let strMeasure15: String?
    let strMeasure16: String?
    let strMeasure17: String?
    let strMeasure18: String?
    let strMeasure19: String?
    let strMeasure20: String?
    
    var id: String { idRecipe }
    
    enum CodingKeys: String, CodingKey {
        case idRecipe      = "idMeal"
        case strRecipe     = "strMeal"
        case strCategory
        case strArea
        case strInstructions
        case strRecipeThumb = "strMealThumb"
        case strTags
        case strSource
        
        case strIngredient1, strIngredient2, strIngredient3, strIngredient4, strIngredient5
        case strIngredient6, strIngredient7, strIngredient8, strIngredient9, strIngredient10
        case strIngredient11, strIngredient12, strIngredient13, strIngredient14, strIngredient15
        case strIngredient16, strIngredient17, strIngredient18, strIngredient19, strIngredient20
        
        case strMeasure1, strMeasure2, strMeasure3, strMeasure4, strMeasure5
        case strMeasure6, strMeasure7, strMeasure8, strMeasure9, strMeasure10
        case strMeasure11, strMeasure12, strMeasure13, strMeasure14, strMeasure15
        case strMeasure16, strMeasure17, strMeasure18, strMeasure19, strMeasure20
    }
    
    // Derived
    var ingredients: [String] {
        let pairs = [
            (strIngredient1, strMeasure1),
            (strIngredient2, strMeasure2),
            (strIngredient3, strMeasure3),
            (strIngredient4, strMeasure4),
            (strIngredient5, strMeasure5),
            (strIngredient6, strMeasure6),
            (strIngredient7, strMeasure7),
            (strIngredient8, strMeasure8),
            (strIngredient9, strMeasure9),
            (strIngredient10, strMeasure10),
            (strIngredient11, strMeasure11),
            (strIngredient12, strMeasure12),
            (strIngredient13, strMeasure13),
            (strIngredient14, strMeasure14),
            (strIngredient15, strMeasure15),
            (strIngredient16, strMeasure16),
            (strIngredient17, strMeasure17),
            (strIngredient18, strMeasure18),
            (strIngredient19, strMeasure19),
            (strIngredient20, strMeasure20)
        ]
        var result: [String] = []
        for (ingredient, measure) in pairs {
            let ing = ingredient?.trimmingCharacters(in: .whitespacesAndNewlines) ?? ""
            let meas = measure?.trimmingCharacters(in: .whitespacesAndNewlines) ?? ""
            if !ing.isEmpty {
                result.append(meas.isEmpty ? ing : "\(meas) \(ing)")
            }
        }
        return result
    }
    
    var ingredientCount: Int { ingredients.count }
    
    var tagList: [String] {
        (strTags ?? "")
            .split(separator: ",")
            .map { $0.trimmingCharacters(in: .whitespacesAndNewlines) }
            .filter { !$0.isEmpty }
    }
    
    var shortInstructions: String {
        let text = strInstructions ?? ""
        if text.count <= 140 { return text }
        if let idx = text.index(text.startIndex, offsetBy: 140, limitedBy: text.endIndex) {
            return String(text[..<idx]) + "…"
        }
        return text
    }
}
